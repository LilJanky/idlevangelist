ALIASES = {'\u2013': '-', '\u2019': "'", '\u2018': "'", '\u201c': '"', '\u201d': '"', '\u2212': '-'}
for c in 'abcdefghijklmnopqrstuvwxyz':
    ALIASES[c] = c.upper()

PX = 100  # font units per pixel; 7 pixels tall = 700 units = 1 em
ADV = 600


def extent(rows):
    cols = [i for row in rows for i, ch in enumerate(row) if ch == '#']
    return min(cols), max(cols)


def glyph_for(rows, shift=0):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        c = 0
        while c < 5:
            if row[c] != '#':
                c += 1
                continue
            start = c
            while c < 5 and row[c] == '#':
                c += 1
            x0, x1 = (start - shift) * PX, (c - shift) * PX
            y1 = (7 - r) * PX
            y0 = y1 - PX
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()


order = ['.notdef', 'space']
glyphs = {'.notdef': glyph_for(('#####',) + ('#...#',) * 5 + ('#####',)), 'space': TTGlyphPen(None).glyph()}
cmap = {32: 'space', 0xA0: 'space'}
names = {}
adv = {'.notdef': ADV, 'space': 400}
for ch, rows in G.items():
    name = 'uni%04X' % ord(ch)
    names[ch] = name
    order.append(name)
    if ch.isdigit():
        glyphs[name] = glyph_for(rows)
        adv[name] = ADV
    else:
        lo, hi = extent(rows)
        glyphs[name] = glyph_for(rows, lo)
        adv[name] = (hi - lo + 2) * PX
    cmap[ord(ch)] = name
for alias, target in ALIASES.items():
    cmap[ord(alias)] = names[target]

fb = FontBuilder(700, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (adv[n], 0) for n in order})
fb.setupHorizontalHeader(ascent=700, descent=-100)
fb.setupNameTable({'familyName': 'IdleVangelist Pixel', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=700, sTypoDescender=-100, usWinAscent=700, usWinDescent=100)
fb.setupPost(isFixedPitch=1)
buf = io.BytesIO()
fb.save(buf)
data = buf.getvalue()
b64 = base64.b64encode(data).decode('ascii')
print('font bytes', len(data), 'glyphs', len(order))

css_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'styles.css')
css = open(css_path, encoding='utf-8', newline='').read()
block = ("/* PIXEL-FONT:START (generated by tools/make-pixel-font.py) */\n"
         "@font-face { font-family: 'IV Pixel'; src: url(data:font/ttf;base64," + b64 + ") format('truetype'); font-display: block; }\n"
         "/* PIXEL-FONT:END */")
if 'PIXEL-FONT:START' in css:
    css = re.sub(r'/\* PIXEL-FONT:START.*?PIXEL-FONT:END \*/', lambda m: block, css, flags=re.S)
else:
    css = block + '\n' + css
open(css_path, 'w', encoding='utf-8', newline='').write(css)
